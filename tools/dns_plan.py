#!/usr/bin/env python3
"""Writes a Cloudflare-importable DNS zone file and prints the matching checklist.
Pure standard library. Run from the project folder:

  python3 tools/dns_plan.py --domain otiarchitects.com.pg --host github --gh-user YOURNAME --mail routing
  python3 tools/dns_plan.py --domain otiarchitects.com.pg --host cloudflare-pages --project otiarchitects --mail workspace

--host   github | cloudflare-pages        where the website files are published
--mail   routing | workspace | none       routing = free Cloudflare Email Routing forwarding to Gmail
                                          workspace = paid Google Workspace mailboxes on your own domain
Import the file in Cloudflare: DNS > Records > Import and Export > Import.
Imported records are DNS-only (grey cloud) unless a record carries a cf-proxied tag; check the icon after importing."""
import argparse, json, os, re, sys
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
site = json.load(open(ROOT + '/content/site.json', encoding='utf-8'))
ap = argparse.ArgumentParser()
ap.add_argument('--domain', default=re.sub(r'^https?://(www\.)?|/.*$', '', site.get('url', '')))
ap.add_argument('--host', choices=['github', 'cloudflare-pages'], default='github')
ap.add_argument('--gh-user', default='YOUR-GITHUB-USERNAME')
ap.add_argument('--project', default='otiarchitects', help='Cloudflare Pages project name')
ap.add_argument('--mail', choices=['routing', 'workspace', 'none'], default='routing')
ap.add_argument('--ttl', type=int, default=3600)
ap.add_argument('--out', default=ROOT + '/deploy/cloudflare-zone.txt')
a = ap.parse_args()
dom = a.domain.strip().lower().rstrip('.')
if not re.fullmatch(r'(?=.{4,253}$)([a-z0-9]([a-z0-9-]{0,61}[a-z0-9])?\.)+[a-z]{2,}', dom):
    sys.exit('Give the live domain, for example --domain otiarchitects.com.pg (or fill "url" in content/site.json).')
T = a.ttl; L = [f'; DNS zone for {dom}. Generated by tools/dns_plan.py', f'$ORIGIN {dom}.', f'$TTL {T}', '']
if a.host == 'github':
    L += ['; Website on GitHub Pages (keep these DNS-only / grey cloud so GitHub can issue the HTTPS certificate)']
    L += [f'@ {T} IN A {ip}' for ip in ('185.199.108.153', '185.199.109.153', '185.199.110.153', '185.199.111.153')]
    L += [f'@ {T} IN AAAA {ip}' for ip in ('2606:50c0:8000::153', '2606:50c0:8001::153', '2606:50c0:8002::153', '2606:50c0:8003::153')]
    L += [f'www {T} IN CNAME {a.gh_user.lower()}.github.io.']
else:
    L += ['; Website on Cloudflare Pages (Cloudflare flattens the CNAME at the root; set the custom domain in the Pages project first)']
    L += [f'@ {T} IN CNAME {a.project}.pages.dev.', f'www {T} IN CNAME {a.project}.pages.dev.']
L += ['']
if a.mail == 'workspace':
    L += ['; Google Workspace mail: one MX record, one SPF record. Add DKIM from Admin console > Apps > Google Workspace > Gmail > Authenticate email',
          f'@ {T} IN MX 1 smtp.google.com.', f'@ {T} IN TXT "v=spf1 include:_spf.google.com ~all"',
          f'_dmarc {T} IN TXT "v=DMARC1; p=none"']
elif a.mail == 'routing':
    L += ['; Mail: do NOT type MX or SPF here. In Cloudflare open Email > Email Routing > Enable, and press "Add records and enable".',
          '; Cloudflare then creates the correct MX and SPF records itself.',
          f'_dmarc {T} IN TXT "v=DMARC1; p=none"']
os.makedirs(os.path.dirname(a.out), exist_ok=True); open(a.out, 'w', encoding='utf-8').write('\n'.join(L) + '\n')
print(f'Wrote {os.path.relpath(a.out, ROOT)} ({len([l for l in L if l and not l.startswith((";", "$"))])} records)\n')
steps = ['Add the site to Cloudflare (free plan). Cloudflare scans for records; delete nothing you still need.',
         'Import deploy/cloudflare-zone.txt (DNS > Records > Import and Export). Check each GitHub Pages record is grey cloud (DNS only).',
         f'At the .pg registry (PNG DNS Administration, Unitech Lae) ask for the name servers of {dom} to be changed to the two Cloudflare name servers shown in your dashboard. Allow up to 24 to 72 hours.']
if a.host == 'github': steps += [f'GitHub repository > Settings > Pages: set Custom domain to www.{dom} (or {dom}), then tick Enforce HTTPS once it appears.']
else: steps += ['Cloudflare dashboard > Workers & Pages > your project > Custom domains: add the domain and www.']
if a.mail == 'routing': steps += ['Cloudflare > Email > Email Routing: enable, add info@ (and any other addresses) that forward to otiarchitects@gmail.com, verify the destination from the Gmail inbox.',
                                  'Gmail > Settings > Accounts and Import > Send mail as: add info@ so you can reply from the firm address (use "Treat as an alias").',
                                  'Edit the SPF record Cloudflare created so it also contains include:_spf.google.com (only one SPF record is allowed), for example: v=spf1 include:_spf.mx.cloudflare.net include:_spf.google.com ~all']
if a.mail == 'workspace': steps += ['Google Admin: verify the domain, turn on DKIM and publish the google._domainkey TXT record it gives you, then change DMARC from p=none to p=quarantine after two weeks of clean reports.']
steps += ['In content/site.json set "url" to https://' + dom + ', set "cdn": "cloudflare" if the orange cloud/Cloudflare Pages is used, and (when the address works) set "email" to info@' + dom + '. Run python3 build.py and push.',
          'Cloudflare > SSL/TLS: set mode Full (strict), turn on Always Use HTTPS and DNSSEC (then add the DS record at the registry). Test with securityheaders.com.']
for i, s in enumerate(steps, 1): print(f'{i}. {s}')
